#!/usr/bin/env python3
"""One-time prep: outline the Backplane lockup into paths-only SVGs.

Reproduces Backplane.Works/brand/backplane-x-banner.html (mark 210 px, 44 px
gap, "backplane" in Berkeley Mono weight 500 at 150 px, line-height 1,
letter-spacing -0.055em, vertically centred) with every glyph converted to
outline paths. The font is not redistributed; only the outlined SVGs are kept,
and the footprint generator reads nothing but those SVGs.

usage: outline_wordmark.py <berkeley-mono-variable.woff2> <backplane-mark.svg>
needs: fonttools, brotli
"""
import re, sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

HERE = Path(__file__).resolve().parent
TEXT, SIZE, TRACK, MARK_PX, GAP = 'backplane', 150.0, -0.055, 210.0, 44.0

def main(font_path, mark_path):
    font = instantiateVariableFont(TTFont(font_path), {'wght': 500, 'wdth': 100, 'slnt': 0})
    upm = font['head'].unitsPerEm
    os2 = font['OS/2']
    asc, desc = os2.sTypoAscender, -os2.sTypoDescender  # USE_TYPO_METRICS is set
    k = SIZE / upm
    box_h = max(MARK_PX, SIZE)
    # CSS line-height:1 box of SIZE px, centred against the 210 px image.
    line_top = (box_h - SIZE) / 2
    baseline = line_top + (SIZE - (asc + desc) * k) / 2 + asc * k
    gs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font['hmtx']
    x = MARK_PX + GAP
    glyph_paths = []
    for ch in TEXT:
        name = cmap[ord(ch)]
        pen = SVGPathPen(gs, ntos=lambda v: f'{v:.4f}'.rstrip('0').rstrip('.'))
        gs[name].draw(TransformPen(pen, (k, 0, 0, -k, x, baseline)))
        glyph_paths.append((ch, pen.getCommands()))
        x += hmtx[name][0] * k + TRACK * SIZE
    width = x - TRACK * SIZE  # trailing tracking is not part of the ink box
    mark_d = re.search(r' d="([^"]+)"', Path(mark_path).read_text()).group(1)
    s = MARK_PX / 256
    mark = (f'<path id="mark" fill-rule="evenodd" transform="scale({s:.8f})" d="{mark_d}"/>')
    words = '\n'.join(f'<path id="glyph-{i}-{c}" fill-rule="nonzero" d="{d}"/>'
                      for i, (c, d) in enumerate(glyph_paths))
    head = '<?xml version="1.0" encoding="UTF-8"?>\n<!-- generated by outline_wordmark.py; outlines only, no live text -->\n'
    (HERE / 'backplane-lockup-horizontal.svg').write_text(
        head + f'<svg xmlns="http://www.w3.org/2000/svg" width="{width:.3f}" height="{box_h:.3f}" '
        f'viewBox="0 0 {width:.3f} {box_h:.3f}" fill="#e6e9de">\n{mark}\n<g id="wordmark">\n{words}\n</g>\n</svg>\n')
    print(f'lockup {width:.2f} x {box_h:.2f} px, baseline {baseline:.3f}, x-height {os2.sxHeight*k:.2f} px')

if __name__ == '__main__':
    main(*sys.argv[1:3])
